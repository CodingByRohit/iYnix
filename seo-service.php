    <script>
        (function () {
            const slider = document.querySelector('.ss-c-slider');
            if (!slider) return;

            const track = slider.querySelector('.ss-c-track');
            const prev = slider.querySelector('.ss-c-prev');
            const next = slider.querySelector('.ss-c-next');

            let cards = Array.from(track.children);

            function getVisible() {
                if (window.innerWidth < 768) return 1;
                if (window.innerWidth < 992) return 2;
                return 3;
            }

            let visible = getVisible();

            // CLONE FOR LOOP
            cards.slice(-visible).forEach(el => {
                track.insertBefore(el.cloneNode(true), track.firstChild);
            });

            cards.slice(0, visible).forEach(el => {
                track.appendChild(el.cloneNode(true));
            });

            let allCards = Array.from(track.children);
            let index = visible;

            function update() {
                const gap = 20;
                const cardWidth = allCards[0].getBoundingClientRect().width + gap;
                track.style.transform = `translateX(-${index * cardWidth}px)`;

                allCards.forEach(c => c.classList.remove('is-active'));

                const center = index + Math.floor((getVisible() - 1) / 2);
                if (allCards[center]) {
                    allCards[center].classList.add('is-active');
                }
            }

            function nextSlide() {
                index++;
                track.style.transition = 'transform 0.5s ease';
                update();

                if (index >= allCards.length - visible) {
                    setTimeout(() => {
                        track.style.transition = 'none';
                        index = visible;
                        update();
                    }, 500);
                }
            }

            function prevSlide() {
                index--;
                track.style.transition = 'transform 0.5s ease';
                update();

                if (index <= 0) {
                    setTimeout(() => {
                        track.style.transition = 'none';
                        index = allCards.length - (visible * 2);
                        update();
                    }, 500);
                }
            }

            next.addEventListener('click', nextSlide);
            prev.addEventListener('click', prevSlide);

            window.addEventListener('resize', () => {
                visible = getVisible();
                update();
            });

            window.addEventListener('load', update);
        })();
    </script>


